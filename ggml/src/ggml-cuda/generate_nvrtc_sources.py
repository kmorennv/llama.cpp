#!/usr/bin/env python3
"""Embed ggml CUDA sources for runtime compilation."""

import argparse
import hashlib
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    sources = []
    for directory in (args.root / "include", args.root / "src", args.root / "src/ggml-cuda"):
        for path in sorted(directory.iterdir()):
            if path.suffix in (".h", ".cuh", ".cu"):
                sources.append((path.name, path.read_text(encoding="utf-8")))
    digest = hashlib.sha256()
    lines = ["// Generated by generate_nvrtc_sources.py.\n",
             "static const char * nvrtc_source_names[] = {\n"]
    for name, source in sources:
        digest.update(name.encode() + b"\0" + source.encode())
        lines.append(f'    "{name}",\n')
    lines.append("};\nstatic const char * nvrtc_source_text[] = {\n")
    for _, source in sources:
        if ')ggml_nvrtc"' in source:
            raise ValueError("source contains raw string delimiter")
        lines.append('R"ggml_nvrtc(' + source + ')ggml_nvrtc",\n')
    lines.append('};\nstatic const char * nvrtc_source_digest = "' + digest.hexdigest() + '";\n')
    args.output.write_text("".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
